def kpi_html(display, label, hue):
    m = re.match(r"^([^\d]*)(\d+(?:\.\d+)?)(.*)$", display)
    if m:
        pre, num, suf = m.groups()
        dec = len(num.split(".")[1]) if "." in num else 0
        attrs = f' data-to="{num}"' + (f' data-pre="{esc(pre)}"' if pre else "") + (f' data-suf="{esc(suf)}"' if suf else "") + (f' data-dec="{dec}"' if dec else "")
        val = f'<b class="num"{attrs}>{esc(display)}</b>'
    else:
        val = f"<b>{esc(display)}</b>"
    return f'<div class="card" data-c="{hue}">{val}<span>{esc(label)}</span></div>'

