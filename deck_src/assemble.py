def data_uri(path):
    ext = os.path.splitext(path)[1].lower().lstrip(".")
    mime = {"png": "image/png", "webp": "image/webp", "jpg": "image/jpeg", "jpeg": "image/jpeg", "svg": "image/svg+xml"}[ext]
    return f"data:{mime};base64," + base64.b64encode(open(path, "rb").read()).decode("ascii")

def shots_for(key, n_features):
    """Return {k: path} for k in 0..n-1 (feature screens), plus 'hero' and 'thumb'. Missing feature screens fall back to the hero."""
    d = P("assets", "shots", key)
    if not os.path.isdir(d):
        return None
    files = sorted(f for f in os.listdir(d) if f.endswith(".webp"))
    by = {}
    for f in files:
        m = re.match(r"(\d\d)", f)
        if m: by.setdefault(int(m.group(1)), os.path.join(d, f))
    hero = by.get(0) or (by[min(by)] if by else None)
    out = {k: by.get(k + 1, hero) for k in range(n_features)}
    out["hero"] = hero
    out["thumb"] = os.path.join(d, "thumb.webp") if os.path.exists(os.path.join(d, "thumb.webp")) else hero
    return out

